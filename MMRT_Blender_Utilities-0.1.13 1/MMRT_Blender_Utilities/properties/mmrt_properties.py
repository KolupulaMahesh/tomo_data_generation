# --------------------------------------------------------
#   Register / Unregister for PropertyGroups & Scene props
# --------------------------------------------------------
classes = (
    MMRTGenerationLogLine,
    MMRTSettings,
)

def register():
    for cls in classes:
        bpy.utils.register_class(cls)

    bpy.types.Scene.mmrt_settings = bpy.props.PointerProperty(type=MMRTSettings)
    bpy.types.WindowManager.mmrt_generation_log = bpy.props.CollectionProperty(type=MMRTGenerationLogLine)
    bpy.types.WindowManager.mmrt_generation_log_index = bpy.props.IntProperty(default=0)
    bpy.types.WindowManager.mmrt_generation_log_status = bpy.props.StringProperty(default="No generation run yet")
    bpy.types.WindowManager.mmrt_generation_log_follow = bpy.props.BoolProperty(
        name="Follow Latest", description="Keep the newest log entry selected", default=True
    )
    bpy.types.WindowManager.mmrt_generation_log_expanded = bpy.props.BoolProperty(
        name="Show Generation Log", default=True
    )

def unregister():
    del bpy.types.WindowManager.mmrt_generation_log_expanded
    del bpy.types.WindowManager.mmrt_generation_log_follow
    del bpy.types.WindowManager.mmrt_generation_log_status
    del bpy.types.WindowManager.mmrt_generation_log_index
    del bpy.types.WindowManager.mmrt_generation_log
    del bpy.types.Scene.mmrt_settings

    for cls in reversed(classes):
        bpy.utils.unregister_class(cls)
