# Blender's dynamic EnumProperty callback requires its item strings to remain
# referenced for the lifetime of the property group.
_PLANNER_ITEMS = {
    pipeline: [
        (planner_id, planner_id, "")
        for planner_id in MMRTPlannerConfig.planner_ids(pipeline)
    ]
    for pipeline in MMRTPlannerConfig.PIPELINES
}


def planner_id_items(self, context):
    return _PLANNER_ITEMS.get(self.plan_pipeline, _PLANNER_ITEMS[MMRTPlannerConfig.DEFAULT_PIPELINE])


def update_plan_pipeline(self, context):
    valid_ids = MMRTPlannerConfig.planner_ids(self.plan_pipeline)
    if valid_ids and self.plan_id not in valid_ids:
        self.plan_id = valid_ids[0]


